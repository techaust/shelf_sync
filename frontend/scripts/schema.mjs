// Generates src/api/schema.d.ts (the API's TypeScript types) from the backend's OpenAPI schema (04 section 2:
// openapi-typescript). The schema comes from scripts/export_openapi.py, which imports create_app (the app serves
// no schema route). Needs uv and the locked Python packages (`uv sync --locked` at the repository root).
//
// Usage (from frontend/):  node scripts/schema.mjs           write src/api/schema.d.ts
//                          node scripts/schema.mjs --check   exit 1 if it isn't current (CI)
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const frontend = join(here, "..");
const repo = join(frontend, "..");
const target = join(frontend, "src", "api", "schema.d.ts");

const exported = spawnSync(
  "uv",
  ["run", "--locked", "python", "-B", join("frontend", "scripts", "export_openapi.py")],
  {
    cwd: repo,
    env: { ...process.env, PYTHONPATH: "backend" },
    encoding: "utf8",
    shell: false,
  },
);
if (exported.status !== 0) {
  console.error("Couldn't export the OpenAPI schema (is `uv sync --locked` done at the repository root?)");
  console.error(exported.stderr || exported.error?.message || "");
  process.exit(1);
}

const schema = JSON.parse(exported.stdout);
const header = "// Generated by frontend/scripts/schema.mjs from the backend's OpenAPI schema. Do not edit.\n";
const contents = header + astToString(await openapiTS(schema)).replaceAll("\r\n", "\n");

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8").replaceAll("\r\n", "\n") : "";
  if (current !== contents) {
    console.error("src/api/schema.d.ts is out of date with the backend: run `npm run schema` and commit it");
    process.exit(1);
  }
  console.log("src/api/schema.d.ts is current");
} else {
  writeFileSync(target, contents);
  console.log("wrote src/api/schema.d.ts");
}
