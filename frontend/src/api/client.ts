// The one API client (SYS-03, the page's side; contract in docs/runs/m1a.2-security.md section 3).
// - Same origin only: every path starts with /api/, and the browser sends the session cookie by itself
//   (credentials "same-origin"). The cookie is HttpOnly: this code never reads, stores or sends it by hand.
// - Every write (any method except GET and HEAD) carries X-ShelfSync: 1; the browser adds the page's Origin.
// - Error text holds the method, the path and the status only: never a request body, so never a ticket.
// - A 401 "signed_out" from any call tells the session store, which shows the signed-out state. No retry.

import type { components } from "./schema";

export const CSRF_HEADER = "X-ShelfSync";
export const CSRF_VALUE = "1";

/** The fixed error codes the backend sends (`{"error": "<code>"}`), typed from the OpenAPI schema
 *  (src/api/schema.d.ts, regenerated by `npm run schema`); anything else is ignored, never echoed. */
export type ErrorCode = components["schemas"]["ErrorResponse"]["error"];

// A record keyed by the schema's union: tsc fails if the backend adds or drops a code and this isn't updated, so
// the list can't drift from the schema (the schema itself is checked current in CI by `npm run schema:check`).
const KNOWN_CODES: Record<ErrorCode, true> = {
  forbidden: true,
  signed_out: true,
  bad_token: true,
  bad_ticket: true,
  invalid_request: true,
  internal: true,
  // Updates (M1b.2): 409 with one of these, 429 too_soon, 422 confirm_required
  development_build: true,
  busy: true,
  no_key: true,
  nothing_to_install: true,
  no_previous: true,
  no_backup: true,
  files_changed: true,
  manifest_invalid: true,
  manifest_missing: true,
  cannot_restart: true,
  too_soon: true,
  confirm_required: true,
  // Stores (M2.1): 404 not_found; 409 store_exists, code_taken, keys_missing, busy; 422 keys_required; 503 secrets_unavailable
  not_found: true,
  store_exists: true,
  code_taken: true,
  keys_missing: true,
  keys_required: true,
  secrets_unavailable: true,
  // Backup export and import (M2.4): 422 export_invalid, passphrase_required, wrong_passphrase; 409 export_too_new, import_needs_empty
  export_invalid: true,
  passphrase_required: true,
  wrong_passphrase: true,
  export_too_new: true,
  import_needs_empty: true,
};
export const ERROR_CODES = Object.keys(KNOWN_CODES) as readonly ErrorCode[];

function isErrorCode(value: unknown): value is ErrorCode {
  return typeof value === "string" && Object.hasOwn(KNOWN_CODES, value);
}

export type HttpMethod = "GET" | "HEAD" | "POST" | "PUT" | "PATCH" | "DELETE";

export class ApiError extends Error {
  readonly method: HttpMethod;
  readonly path: string;
  readonly status: number;
  readonly code: ErrorCode | null;

  constructor(method: HttpMethod, path: string, status: number, code: ErrorCode | null) {
    super(`${method} ${path} answered HTTP ${status}${code ? ` (${code})` : ""}`);
    this.name = "ApiError";
    this.method = method;
    this.path = path;
    this.status = status;
    this.code = code;
  }
}

/** The request never reached ShelfSync (the server is stopped, or the network layer refused it). */
export class ApiUnreachableError extends Error {
  readonly method: HttpMethod;
  readonly path: string;

  constructor(method: HttpMethod, path: string) {
    super(`${method} ${path} got no answer`);
    this.name = "ApiUnreachableError";
    this.method = method;
    this.path = path;
  }
}

export function isWrite(method: HttpMethod): boolean {
  return method !== "GET" && method !== "HEAD";
}

const API_PATH = /^\/api\/[A-Za-z0-9/_-]*$/;

export interface ApiClientOptions {
  fetch?: typeof fetch;
  onSignedOut?: () => void;
}

export interface ApiClient {
  /** `signal` ends a request that waits too long (the restart poll's health and session checks). */
  request(method: HttpMethod, path: string, body?: unknown, signal?: AbortSignal): Promise<Response>;
  get<T>(path: string, signal?: AbortSignal): Promise<T>;
  send<T = void>(method: Exclude<HttpMethod, "GET" | "HEAD">, path: string, body?: unknown): Promise<T>;
}

async function errorCode(response: Response): Promise<ErrorCode | null> {
  try {
    const body: unknown = await response.json();
    if (body && typeof body === "object" && "error" in body) {
      const code = (body as { error: unknown }).error;
      if (isErrorCode(code)) return code;
    }
  } catch {
    // Not JSON (a 404 from the static files, a 405): no code.
  }
  return null;
}

export function createApiClient(options: ApiClientOptions = {}): ApiClient {
  const doFetch = options.fetch ?? ((input, init) => globalThis.fetch(input, init));

  async function request(method: HttpMethod, path: string, body?: unknown, signal?: AbortSignal): Promise<Response> {
    if (!API_PATH.test(path)) throw new Error(`Not an API path: ${path.slice(0, 80)}`);
    const headers: Record<string, string> = { Accept: "application/json" };
    if (isWrite(method)) headers[CSRF_HEADER] = CSRF_VALUE;
    const init: RequestInit = {
      method,
      headers,
      credentials: "same-origin",
      mode: "same-origin",
      cache: "no-store",
      redirect: "error",
      referrerPolicy: "no-referrer",
    };
    if (signal) init.signal = signal;
    if (body !== undefined) {
      headers["Content-Type"] = "application/json";
      init.body = JSON.stringify(body);
    }
    try {
      return await doFetch(path, init);
    } catch {
      // The browser's own message is dropped: it can't hold the body, but nothing here repeats what it was sent.
      throw new ApiUnreachableError(method, path);
    }
  }

  async function checked(method: HttpMethod, path: string, body?: unknown, signal?: AbortSignal): Promise<Response> {
    const response = await request(method, path, body, signal);
    if (response.ok) return response;
    const code = await errorCode(response);
    if (response.status === 401 && code === "signed_out") options.onSignedOut?.();
    throw new ApiError(method, path, response.status, code);
  }

  return {
    request,
    async get<T>(path: string, signal?: AbortSignal): Promise<T> {
      const response = await checked("GET", path, undefined, signal);
      return (await response.json()) as T;
    },
    async send<T = void>(method: Exclude<HttpMethod, "GET" | "HEAD">, path: string, body?: unknown): Promise<T> {
      const response = await checked(method, path, body);
      if (response.status === 204) return undefined as T;
      return (await response.json()) as T;
    },
  };
}
