// Icon frames (app icon, favicon, tray states) as canvases, and favicon.svg. Every number comes from geometry.mjs.
import { APP_ICON, TRAY, VERSIONS, mark } from "../geometry.mjs";
import { Canvas, circlePath, rectPath, roundRectPath } from "./render.mjs";
import { hex, semantic } from "./tokens.mjs";
import { TITLE } from "./lockups.mjs";

const markLayers = (m, version) => [
  { d: m.base, color: VERSIONS[version].base },
  { d: m.accent, color: VERSIONS[version].accent },
];

/** One app-icon frame: the dark symbol on an ink plate (see APP_ICON). */
export function appFrame(px) {
  const c = new Canvas(px, px);
  const rad = px <= 16 ? 0 : Math.round(px * APP_ICON.radius);
  c.draw([{ d: roundRectPath(0, 0, px, px, rad), color: APP_ICON.plate }]);
  const fitted = APP_ICON.fittedSymbol[px];
  if (fitted) {
    const off = (px - fitted) / 2;
    c.draw(markLayers(mark(fitted), APP_ICON.version), { dx: off, dy: off });
  } else {
    const size = px * APP_ICON.smoothRatio;
    const off = (px - size) / 2;
    c.draw(markLayers(mark(), APP_ICON.version), { s: size / 100, dx: off, dy: off });
  }
  return c;
}

/** The state badge's geometry at `px` (all in whole pixels, bottom-right corner). */
export function badgeGeometry(px, state) {
  const b = TRAY.badge[px];
  if (state === "paused") {
    const w = 3 * b.bar, x0 = px - w, y0 = px - b.box;
    return {
      knockout: rectPath(x0 - b.gap, y0 - b.gap, w + b.gap, b.box + b.gap),
      shape: rectPath(x0, y0, b.bar, b.box) + rectPath(x0 + 2 * b.bar, y0, b.bar, b.box),
      box: { x: x0, y: y0, w, h: b.box },
    };
  }
  const rad = b.box / 2, cx = px - rad, cy = px - rad;
  const m = mark(px), v = m.p.v, y1 = m.f.y1;
  return {
    // The same rule as the paused badge: the badge box plus its gap, cleared as a whole-pixel square (it also clears
    // the right stem's columns below the spine), so at least one fully clear pixel separates the dot from the ink,
    // along sides and corners alike.
    knockout: rectPath(px - b.box - b.gap, px - b.box - b.gap, b.box + b.gap, b.box + b.gap) + rectPath(px - v, y1, v, px - y1),
    shape: circlePath(cx, cy, rad),
    box: { x: px - b.box, y: px - b.box, w: b.box, h: b.box },
  };
}

/** One tray frame: the fitted symbol for a light or dark taskbar, with the state's badge. */
export function trayFrame(px, taskbar, state) {
  const version = TRAY.taskbars[taskbar];
  const c = new Canvas(px, px);
  c.draw(markLayers(mark(px), version));
  if (state === "normal") return c;
  const g = badgeGeometry(px, state);
  c.erase(g.knockout, {}, { snap: true }); // whole pixels: at least one clear pixel between ink and badge
  c.draw([{ d: g.shape, color: semantic(TRAY.status[state], taskbar) }]);
  return c;
}

/** favicon.svg: the symbol fitted to a 16-unit grid, switching to the dark colours in a dark browser. */
export function faviconSvg() {
  const m = mark(16);
  const L = VERSIONS.color, D = VERSIONS.dark;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16"><title>${TITLE}</title>` +
    `<!-- Generated by brand/scripts/build.mjs. Pixel-fitted at 16 px; colours palette.${L.base} / ${L.accent}, dark palette.${D.base} / ${D.accent}. -->` +
    `<style>.b{fill:${hex(L.base)}}.a{fill:${hex(L.accent)}}@media (prefers-color-scheme:dark){.b{fill:${hex(D.base)}}.a{fill:${hex(D.accent)}}}</style>` +
    `<path class="b" d="${m.base}"/><path class="a" d="${m.accent}"/></svg>\n`;
}
