// Standalone SVGs: the symbol (vector and pixel-fitted), the colour-split variants and the four lockups.
import { ENDORSE, LOCKUP, MINIMUM, STROKE, VARIANTS, mark } from "./geometry.mjs";
import { PALETTE } from "./measure.mjs";

const r = (n) => Math.round(n * 100) / 100;

/** Colour schemes: token names only; the hex values come from PALETTE (TecHaust tokens.json). */
export const SCHEMES = {
  light: { label: "full colour, for light backgrounds", base: "ink-900", accent: "verdigris-700", text: "ink-900" },
  dark: { label: "for dark backgrounds", base: "mist", accent: "verdigris-300", text: "mist" },
  mono: { label: "one colour, ink", base: "ink-900", accent: "ink-900", text: "ink-900" },
};

const style = (s) => `  <!-- Patina colours from techaust_platform packages/ui/tokens/tokens.json (read-only); brand/tokens.json replaces them at P3.3. -->
  <style>
    svg {
      --mark-base: ${PALETTE[s.base]}; /* palette.${s.base} */
      --mark-accent: ${PALETTE[s.accent]}; /* palette.${s.accent} */
      --mark-text: ${PALETTE[s.text]}; /* palette.${s.text} */
    }
    .b { fill: var(--mark-base); }
    .a { fill: var(--mark-accent); }
    .w { fill: var(--mark-text); }
  </style>`;
const head = (vb, label, note) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" role="img" aria-label="${label}">
  <title>${label}</title>
  <!-- Generated by brand/draft/build.mjs from brand/draft/geometry.mjs (P3.2 draft). Do not edit by hand. ${note} -->`;

/** Lockup layout in wordmark master units (cap height 100, baseline y = 100). */
export function layout(word, endorse) {
  const markSize = 100 * LOCKUP.markScale;
  const wx = r(markSize + LOCKUP.gap);
  const stroke = r(STROKE * LOCKUP.markScale);
  const y0 = Math.min(LOCKUP.markY, Math.floor(word.bounds.y0));
  const y1 = Math.max(LOCKUP.markY + markSize, Math.ceil(word.bounds.y1));
  const width = r(wx + word.bounds.x1);
  const eTop = r(100 + ENDORSE.gapStrokes * stroke); // endorsement cap line
  const eBottom = r(eTop + endorse.cap);
  // Sizes in CSS px at the minimums.
  const primaryMinScale = MINIMUM.primaryWidth / width;
  const markAtPrimaryMin = r(markSize * primaryMinScale);
  const capAtPrimaryMin = r(100 * primaryMinScale);
  const primaryWidthForSymbolMin = r((MINIMUM.symbol / markSize) * width);
  const endorsedScale = ENDORSE.captionPx / endorse.emSize; // px per unit when the endorsement font size is 12 px
  return {
    markSize, wx, stroke, y0, y1, width, eTop, eBottom,
    vb: { primary: `0 ${y0} ${width} ${r(y1 - y0)}`, wordmark: `0 ${Math.floor(word.bounds.y0)} ${r(word.bounds.x1)} ${r(Math.ceil(word.bounds.y1) - Math.floor(word.bounds.y0))}`, endorsed: `0 ${y0} ${width} ${r(Math.max(y1, eBottom) - y0)}` },
    minimum: {
      primaryWidth: MINIMUM.primaryWidth, markAtPrimaryMin, capAtPrimaryMin, primaryWidthForSymbolMin,
      endorsedWidth: r(width * endorsedScale), endorsedCap: r(100 * endorsedScale), endorsementCapPx: r(endorse.cap * endorsedScale),
    },
  };
}

const markGroup = (m, transform = "") => `<g${transform ? ` transform="${transform}"` : ""}><path class="b" d="${m.base}"/><path class="a" d="${m.accent}"/></g>`;
const wordGroup = (word, x) => `<g class="w" transform="translate(${x} 0)">${word.glyphs.filter(Boolean).map((d) => `<path d="${d}"/>`).join("")}</g>`;

/** Inner markup of each lockup (no <svg> wrapper), shared by the files and the board. */
export function lockupInner(kind, word, endorse, L, variant) {
  const m = mark(variant);
  const placed = markGroup(m, `translate(0 ${LOCKUP.markY}) scale(${LOCKUP.markScale})`);
  if (kind === "symbol") return markGroup(m);
  if (kind === "wordmark") return wordGroup(word, 0);
  const base = placed + wordGroup(word, L.wx);
  if (kind === "primary") return base;
  return base + `<path class="w" transform="translate(${L.wx} ${L.eTop})" d="${endorse.d}"/>`;
}

export function files(word, endorse, L) {
  const out = {};
  const names = { primary: "ShelfSync primary lockup", symbol: "ShelfSync symbol", wordmark: "ShelfSync wordmark", endorsed: "ShelfSync by TecHaust, endorsed lockup" };
  for (const [kind, label] of Object.entries(names)) {
    for (const [sid, s] of Object.entries(SCHEMES)) {
      const vb = kind === "symbol" ? "0 0 100 100" : L.vb[kind];
      const file = `${kind === "symbol" ? "symbol" : `lockup-${kind}`}${sid === "light" ? "" : `-${sid === "dark" ? "on-dark" : "one-colour"}`}.svg`;
      out[file] = `${head(vb, `${label}, ${s.label}`, "")}\n${style(s)}\n  ${lockupInner(kind, word, endorse, L)}\n</svg>\n`;
    }
  }
  for (const v of VARIANTS) {
    const m = mark(v.id);
    out[`variant-${v.id}.svg`] = `${head("0 0 100 100", `ShelfSync symbol, colour split ${v.id[0].toUpperCase()}: ${v.name}`, `Verdigris on ${v.what}.`)}\n${style(SCHEMES.light)}\n  ${markGroup(m)}\n</svg>\n`;
  }
  for (const px of [16, 20, 24, 32, 48, 64]) {
    const m = mark(undefined, px);
    out[`symbol-${px}px.svg`] = `${head(`0 0 ${px} ${px}`, `ShelfSync symbol, pixel-fitted at ${px} px`, `Every edge on a whole pixel; draw at exactly ${px} x ${px} device pixels.`).replace("<svg ", `<svg width="${px}" height="${px}" `)}\n${style(SCHEMES.light)}\n  ${markGroup(m)}\n</svg>\n`;
  }
  return out;
}
