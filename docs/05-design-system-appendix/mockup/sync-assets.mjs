// Copies the brand assets the P3.4 mockup uses into this folder, so the preview server (which serves only
// docs/05-design-system-appendix/) can reach them. Nothing here is drawn or typed by hand:
//   - tokens.css        copied unchanged from brand/generated/tokens.css
//   - tone-dark.css     generated from brand/tokens.json: the dark-theme semantic values scoped to `.tone-dark`,
//                       for the app bar, which is ink in both themes (05 section 2.2)
//   - fonts/            Archivo (variable, wdth + wght) and IBM Plex Mono 400/500 woff2, with their OFL licences
//   - logo/             the approved SVGs from brand/assets/logo/, unchanged
//   - icons/            only the Lucide icons in ICONS below, from lucide-static (pinned in brand/package.json),
//                       its ISC licence, and sprite.svg built from those same files
// Run from the repo root:  node docs/05-design-system-appendix/mockup/sync-assets.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const brand = join(root, "brand");
const nm = join(brand, "node_modules");

// Every icon the mockup screens use. Names are lucide-static 1.55.0's.
export const ICONS = [
  // nav and shell
  "layout-dashboard", "upload", "inbox", "library", "brush-cleaning", "history", "settings",
  "panel-left-close", "panel-left-open", "pause", "play", "hard-drive", "flask-conical",
  // bands and states (05 section 2.4)
  "circle-check", "circle-dot", "circle-help", "search-x", "shield-alert", "shield-x", "shield-question",
  "triangle-alert", "bot", "user-check", "arrow-right",
  // content
  "file-archive", "folder-open", "check", "x", "external-link", "refresh-cw",
  "clipboard-paste", "list-checks", "table", "chart-column", "info", "chevron-right",
  "shield-check", "clock", "file-up",
  // part B
  "globe", "search", "download", "pencil", "trash-2", "link", "unlink", "rotate-ccw", "calendar-clock", "key-round", "lock",
  "plug", "arrow-left", "chevron-left", "store", "fingerprint-pattern", "book-open", "sliders-horizontal", "archive",
  "app-window", "monitor", "sun", "moon", "database", "server", "save", "plus", "file-pen", "arrow-left-right",
  "refresh-ccw", "arrow-up-down", "arrow-down", "undo-2",
];

function copy(from, to) {
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(from, to);
}

// tokens
copy(join(brand, "generated", "tokens.css"), join(here, "tokens.css"));

// dark tone, scoped: every semantic token's dark value, resolved through the palette
const tokens = JSON.parse(readFileSync(join(brand, "tokens.json"), "utf8"));
const resolve = (v) => (v.startsWith("#") ? v : tokens.palette[v]);
const lines = Object.entries(tokens.semantic).map(([k, v]) => `  --color-${k}: ${resolve(v.dark).toLowerCase()};`);
lines.push(`  --elevation-1: ${tokens.shadow["1"].dark};`, `  --elevation-2: ${tokens.shadow["2"].dark};`);
writeFileSync(
  join(here, "tone-dark.css"),
  `/* Generated by sync-assets.mjs from brand/tokens.json (semantic dark values). Do not edit. */\n` +
    `.tone-dark {\n  color-scheme: dark;\n${lines.join("\n")}\n}\n`,
);

// fonts
const archivo = join(nm, "@fontsource-variable", "archivo");
const plex = join(nm, "@fontsource", "ibm-plex-mono");
copy(join(archivo, "files", "archivo-latin-wdth-normal.woff2"), join(here, "fonts", "archivo-latin-wdth-normal.woff2"));
copy(join(archivo, "LICENSE"), join(here, "fonts", "LICENSE-archivo.txt"));
for (const w of ["400", "500"]) {
  copy(join(plex, "files", `ibm-plex-mono-latin-${w}-normal.woff2`), join(here, "fonts", `ibm-plex-mono-latin-${w}-normal.woff2`));
}
copy(join(plex, "LICENSE"), join(here, "fonts", "LICENSE-ibm-plex-mono.txt"));

// logos (only the lockups the shell uses)
for (const f of ["logo-primary-dark.svg"]) {
  copy(join(brand, "assets", "logo", f), join(here, "logo", f));
}
copy(join(brand, "assets", "favicon", "favicon.svg"), join(here, "logo", "favicon.svg"));

// icons
const lucide = join(nm, "lucide-static");
const iconsDir = join(here, "icons");
rmSync(iconsDir, { recursive: true, force: true });
const unique = [...new Set(ICONS)].sort();
const symbols = [];
for (const name of unique) {
  const src = join(lucide, "icons", `${name}.svg`);
  copy(src, join(iconsDir, `${name}.svg`));
  const svg = readFileSync(src, "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${inner.replace(/\s*\n\s*/g, "")}</symbol>`);
}
copy(join(lucide, "LICENSE"), join(iconsDir, "LICENSE-lucide.txt"));
const version = JSON.parse(readFileSync(join(lucide, "package.json"), "utf8")).version;
writeFileSync(
  join(iconsDir, "sprite.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg"><!-- Built by sync-assets.mjs from lucide-static ${version} (ISC, LICENSE-lucide.txt). Do not edit. -->\n${symbols.join("\n")}\n</svg>\n`,
);
console.log(`tokens.css, tone-dark.css, 3 fonts, 2 logo files, ${unique.length} icons + sprite (lucide-static ${version})`);
